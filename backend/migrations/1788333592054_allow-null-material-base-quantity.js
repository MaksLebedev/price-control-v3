// ============================================================
// PRICE CONTROL V3
// Разрешаем materials.base_quantity = NULL
//
// Причина:
//
// Анализ реального листа "МАТ ГЭСН" показал, что существуют
// материалы, у которых исходное количество:
//
// - отсутствует;
// - либо содержит некорректное текстовое значение.
//
// В таких случаях Price Control V3 не должен придумывать
// количество 1.
//
// Поэтому:
// - base_quantity становится nullable;
// - DEFAULT 1 сохраняется.
//
// DEFAULT 1 по-прежнему будет использоваться там, где новое
// значение вообще не передаётся, например при ручном создании
// материала через интерфейс.
//
// Но импортёр сможет явно записать NULL, если количество
// в исходной базе неизвестно.
// ============================================================

/**
 * UP
 *
 * Применяем изменение схемы.
 */
exports.up = (pgm) => {
  // ----------------------------------------------------------
  // Убираем только ограничение NOT NULL.
  //
  // Тип numeric(18,6) НЕ меняется.
  // DEFAULT 1 НЕ меняется.
  // Существующие данные НЕ меняются.
  // ----------------------------------------------------------

  pgm.sql(`
    ALTER TABLE public.materials
      ALTER COLUMN base_quantity DROP NOT NULL;
  `);
};

/**
 * DOWN
 *
 * Откатываем изменение схемы.
 */
exports.down = (pgm) => {
  // ----------------------------------------------------------
  // Перед возвратом NOT NULL обязательно проверяем,
  // появились ли реальные материалы с base_quantity = NULL.
  //
  // Мы специально НЕ заменяем такие NULL на 1.
  //
  // Если NULL уже существуют, обратная миграция остановится
  // с понятной ошибкой. Это безопаснее, чем незаметно менять
  // реальные данные.
  // ----------------------------------------------------------

  pgm.sql(`
    DO $$
    BEGIN
      IF EXISTS (
        SELECT 1
        FROM public.materials
        WHERE base_quantity IS NULL
      ) THEN
        RAISE EXCEPTION
          'Cannot restore NOT NULL on materials.base_quantity: rows with NULL base_quantity exist.';
      END IF;
    END
    $$;
  `);

  // ----------------------------------------------------------
  // Если NULL отсутствуют, возвращаем старое ограничение.
  //
  // DEFAULT 1 при этом также остаётся без изменений.
  // ----------------------------------------------------------

  pgm.sql(`
    ALTER TABLE public.materials
      ALTER COLUMN base_quantity SET NOT NULL;
  `);
};
