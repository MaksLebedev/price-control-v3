// ============================================================
// PRICE CONTROL V3
// РАСШИРЕНИЕ ТАБЛИЦЫ supplier_offers
//
// Эта миграция подготавливает PostgreSQL к переносу
// реальных данных из листа Excel "МАТ ГЭСН".
//
// После анализа старой базы выяснилось:
//
// 1. Excel хранит отдельно:
//    - ручную цену товара магазина;
//    - цену товара от парсера;
//    - рабочую цену за единицу сборника;
//    - рабочую цену после парсинга.
//
// 2. Источником цены не всегда является интернет-магазин.
//    Иногда в Excel указано:
//    - "средняя цена";
//    - "цена заказчика";
//    - "прайс";
//    - "занесено вручную";
//    и т.п.
//
// Поэтому supplier_id должен допускать NULL.
//
// 3. Большинство пересчётов можно описать коэффициентом,
//    но встречаются дополнительные слагаемые и сложные
//    старые Excel-формулы.
//
// Исходную первую миграцию эта миграция НЕ изменяет.
// ============================================================

// ============================================================
// UP
//
// Выполняется при:
//
// npm run migrate:up
//
// Добавляет новые возможности в supplier_offers.
// ============================================================

exports.up = (pgm) => {
  // ----------------------------------------------------------
  // 1. ДЕЛАЕМ supplier_id НЕОБЯЗАТЕЛЬНЫМ
  //
  // Раньше каждое предложение обязательно должно было иметь
  // запись в таблице suppliers.
  //
  // Но в старом Excel существуют рабочие цены с источниками:
  //
  // "средняя цена"
  // "цена заказчика"
  // "прайс"
  //
  // У таких записей конкретного поставщика может не быть.
  //
  // Внешний ключ на suppliers при этом СОХРАНЯЕТСЯ.
  // Если supplier_id указан, он всё равно должен ссылаться
  // на существующего поставщика.
  // ----------------------------------------------------------

  pgm.alterColumn("supplier_offers", "supplier_id", {
    notNull: false,
  });

  // ----------------------------------------------------------
  // 2. ДОБАВЛЯЕМ НОВЫЕ ПОЛЯ
  // ----------------------------------------------------------

  pgm.addColumns("supplier_offers", {
    // ------------------------------------------------------
    // Цена непосредственно товара у поставщика.
    //
    // Старый Excel:
    // колонка H "цена магазин".
    //
    // Например:
    // упаковка товара стоит 1019 руб.
    // ------------------------------------------------------

    source_price: {
      type: "numeric(18,4)",
    },

    // ------------------------------------------------------
    // Последняя цена непосредственно товара,
    // которую получил парсер.
    //
    // Старый Excel:
    // колонка I "цена магазин (парсинг)".
    // ------------------------------------------------------

    last_parsed_source_price: {
      type: "numeric(18,4)",
    },

    // ------------------------------------------------------
    // Дополнительное слагаемое при пересчёте.
    //
    // Большинство строк имеют только коэффициент:
    //
    // новая_цена = цена_магазина * conversion_factor
    //
    // Но встречаются формулы вида:
    //
    // H + 775
    //
    // Для таких строк:
    //
    // conversion_factor = 1
    // conversion_offset = 775
    //
    // По умолчанию дополнительного слагаемого нет.
    // ------------------------------------------------------

    conversion_offset: {
      type: "numeric(18,4)",
      notNull: true,
      default: 0,
    },

    // ------------------------------------------------------
    // Способ пересчёта цены.
    //
    // Пока это обычный текст, чтобы модель можно было
    // развивать без изменения PostgreSQL ENUM.
    //
    // Планируемые значения:
    //
    // factor
    //   обычный пересчёт через коэффициент
    //
    // factor_offset
    //   коэффициент + дополнительное слагаемое
    //
    // manual
    //   рабочая цена задана вручную
    //
    // legacy_formula
    //   сложная формула старого Excel, которую нельзя
    //   безопасно заменить простым коэффициентом
    //
    // Для существующих записей используется "factor".
    // ------------------------------------------------------

    conversion_mode: {
      type: "text",
      notNull: true,
      default: "factor",
    },

    // ------------------------------------------------------
    // Исходная формула колонки J из старого Excel.
    //
    // Нужна для:
    // - проверки миграции;
    // - аудита;
    // - сложных исключений;
    // - понимания происхождения conversion_factor.
    //
    // V3 НЕ должен исполнять этот текст как произвольный код.
    // Это историческая/диагностическая информация.
    // ------------------------------------------------------

    conversion_formula: {
      type: "text",
    },

    // ------------------------------------------------------
    // Исходная формула колонки K из старого Excel.
    //
    // Храним отдельно, потому что старая формула K
    // может отличаться от формулы J.
    //
    // Это также историческая информация.
    // ------------------------------------------------------

    parsed_conversion_formula: {
      type: "text",
    },

    // ------------------------------------------------------
    // Текстовое описание источника цены,
    // когда колонка L старого Excel НЕ содержит URL.
    //
    // Например:
    //
    // "средняя цена"
    // "цена заказчика"
    // "прайс"
    // "занесено вручную"
    // "не используем"
    //
    // Настоящие интернет-ссылки по-прежнему будут
    // храниться в существующем поле url.
    // ------------------------------------------------------

    source_reference: {
      type: "text",
    },
  });
};

// ============================================================
// DOWN
//
// Выполняется при откате миграции.
//
// Задача DOWN — вернуть схему к состоянию,
// которое было до этой миграции.
//
// ВАЖНО:
// если после миграции появятся supplier_offers без supplier_id,
// автоматический возврат supplier_id в NOT NULL может привести
// к потере смысла данных.
//
// Поэтому DOWN сначала проверяет такие записи и,
// если они существуют, ОСТАНАВЛИВАЕТ откат с понятной ошибкой.
// Никакие строки автоматически не удаляются.
// ============================================================

exports.down = (pgm) => {
  // ----------------------------------------------------------
  // 1. ПРОВЕРЯЕМ, МОЖНО ЛИ БЕЗОПАСНО ВЕРНУТЬ NOT NULL
  //
  // Если имеются предложения без supplier_id,
  // откат будет остановлен.
  //
  // Это безопаснее, чем молча удалить такие данные.
  // ----------------------------------------------------------

  pgm.sql(`
    DO $$
    BEGIN
      IF EXISTS (
        SELECT 1
        FROM supplier_offers
        WHERE supplier_id IS NULL
      ) THEN
        RAISE EXCEPTION
          'Cannot rollback migration: supplier_offers contains rows with NULL supplier_id';
      END IF;
    END
    $$;
  `);

  // ----------------------------------------------------------
  // 2. УДАЛЯЕМ ПОЛЯ, ДОБАВЛЕННЫЕ ЭТОЙ МИГРАЦИЕЙ
  // ----------------------------------------------------------

  pgm.dropColumns("supplier_offers", [
    "source_price",
    "last_parsed_source_price",
    "conversion_offset",
    "conversion_mode",
    "conversion_formula",
    "parsed_conversion_formula",
    "source_reference",
  ]);

  // ----------------------------------------------------------
  // 3. ВОЗВРАЩАЕМ supplier_id В ИСХОДНОЕ СОСТОЯНИЕ
  //
  // То есть снова делаем поле обязательным.
  // ----------------------------------------------------------

  pgm.alterColumn("supplier_offers", "supplier_id", {
    notNull: true,
  });
};
