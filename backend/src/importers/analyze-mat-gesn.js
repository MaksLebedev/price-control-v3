// ============================================================
// PRICE CONTROL V3
// АНАЛИЗ ЛИСТА "МАТ ГЭСН" ИЗ EXCEL
//
// Этот файл выполняет ТОЛЬКО чтение и анализ Excel.
//
// Он НЕ:
// - изменяет исходный Excel;
// - записывает данные в PostgreSQL;
// - удаляет данные;
// - создаёт материалы в базе.
//
// Его задача — сначала понять, какие реальные данные
// находятся в листе "МАТ ГЭСН", прежде чем делать импорт.
// ============================================================

const fs = require("fs");
const path = require("path");
const XLSX = require("xlsx");

// ------------------------------------------------------------
// НАЗВАНИЕ ЛИСТА, КОТОРЫЙ МЫ АНАЛИЗИРУЕМ
//
// На данном этапе нас интересует только лист "МАТ ГЭСН".
// Остальные листы Excel этот скрипт не изменяет и не импортирует.
// ------------------------------------------------------------
const TARGET_SHEET_NAME = "МАТ ГЭСН";

// ------------------------------------------------------------
// ПОЛУЧАЕМ ПУТЬ К EXCEL ИЗ КОМАНДНОЙ СТРОКИ
//
// Скрипт запускается примерно так:
//
// node src/importers/analyze-mat-gesn.js "D:\...\База цен верс 0.9.xlsx"
//
// Мы специально НЕ прописываем путь к Excel внутри кода.
//
// Благодаря этому один и тот же анализатор можно будет
// использовать для разных версий базы цен.
// ------------------------------------------------------------
const excelFilePath = process.argv[2];

// ------------------------------------------------------------
// ПРОВЕРКА: ПЕРЕДАН ЛИ ПУТЬ К EXCEL
//
// Если пользователь забыл указать файл,
// скрипт ничего не делает и объясняет, как его запустить.
// ------------------------------------------------------------
if (!excelFilePath) {
  console.error("");
  console.error("Не указан путь к Excel-файлу.");
  console.error("");
  console.error("Пример запуска:");
  console.error(
    'node src/importers/analyze-mat-gesn.js "D:\\путь\\к\\База цен верс 0.9.xlsx"',
  );
  console.error("");

  process.exit(1);
}

// ------------------------------------------------------------
// ПОЛУЧАЕМ ПОЛНЫЙ ПУТЬ К ФАЙЛУ
//
// path.resolve приводит переданный путь
// к стандартному абсолютному виду Windows.
// ------------------------------------------------------------
const resolvedExcelPath = path.resolve(excelFilePath);

// ------------------------------------------------------------
// ПРОВЕРКА: СУЩЕСТВУЕТ ЛИ EXCEL-ФАЙЛ
//
// Если путь указан неправильно,
// останавливаем анализ до попытки открыть файл.
// ------------------------------------------------------------
if (!fs.existsSync(resolvedExcelPath)) {
  console.error("");
  console.error("Excel-файл не найден:");
  console.error(resolvedExcelPath);
  console.error("");

  process.exit(1);
}

// ------------------------------------------------------------
// ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ ДЛЯ ТЕКСТА
//
// Excel может содержать:
// - обычный текст;
// - числа;
// - пустые значения.
//
// Эта функция приводит значение к аккуратной строке,
// чтобы дальше было проще сравнивать заголовки и коды.
// ------------------------------------------------------------
function normalizeText(value) {
  if (value === null || value === undefined) {
    return "";
  }

  return String(value).trim();
}

// ------------------------------------------------------------
// ОСНОВНАЯ ФУНКЦИЯ АНАЛИЗА
//
// Именно здесь происходит чтение Excel
// и сбор диагностической информации.
// ------------------------------------------------------------
function analyzeMatGesn() {
  console.log("");
  console.log("==============================================");
  console.log("Price Control V3 — анализ листа МАТ ГЭСН");
  console.log("==============================================");
  console.log("");

  console.log("Excel:");
  console.log(resolvedExcelPath);
  console.log("");

  // ----------------------------------------------------------
  // ОТКРЫВАЕМ EXCEL В РЕЖИМЕ ЧТЕНИЯ
  //
  // Мы только читаем содержимое файла.
  // XLSX.writeFile здесь нигде не используется,
  // поэтому исходная книга не изменяется.
  // ----------------------------------------------------------
  const workbook = XLSX.readFile(resolvedExcelPath, {
    cellDates: true,
    cellFormula: true,
  });

  // ----------------------------------------------------------
  // ПОКАЗЫВАЕМ ВСЕ ЛИСТЫ КНИГИ
  //
  // Это первая диагностическая проверка.
  // Она позволяет убедиться, что открыта нужная версия Excel.
  // ----------------------------------------------------------
  console.log("Листы Excel:");

  workbook.SheetNames.forEach((sheetName, index) => {
    console.log(`${index + 1}. ${sheetName}`);
  });

  console.log("");

  // ----------------------------------------------------------
  // ПРОВЕРЯЕМ НАЛИЧИЕ ЛИСТА "МАТ ГЭСН"
  //
  // Если лист отсутствует, продолжать анализ нельзя.
  // ----------------------------------------------------------
  if (!workbook.SheetNames.includes(TARGET_SHEET_NAME)) {
    console.error(`Лист "${TARGET_SHEET_NAME}" в Excel не найден.`);

    process.exit(1);
  }

  // ----------------------------------------------------------
  // ПОЛУЧАЕМ ОБЪЕКТ ЛИСТА "МАТ ГЭСН"
  // ----------------------------------------------------------
  const worksheet = workbook.Sheets[TARGET_SHEET_NAME];

  // ----------------------------------------------------------
  // ПРЕОБРАЗУЕМ ЛИСТ В МАССИВ СТРОК
  //
  // header: 1 означает:
  //
  // каждая строка Excel становится массивом:
  //
  // [
  //   значение колонки A,
  //   значение колонки B,
  //   значение колонки C,
  //   ...
  // ]
  //
  // Мы специально пока НЕ связываем колонки
  // с таблицей PostgreSQL.
  //
  // Сначала смотрим реальную структуру исходного файла.
  // ----------------------------------------------------------
  const rows = XLSX.utils.sheet_to_json(worksheet, {
    header: 1,
    raw: false,
    defval: "",
    blankrows: true,
  });

  // ----------------------------------------------------------
  // ОБЩАЯ ИНФОРМАЦИЯ О ЛИСТЕ
  // ----------------------------------------------------------
  console.log(`Анализируемый лист: ${TARGET_SHEET_NAME}`);
  console.log(`Всего считано строк: ${rows.length}`);
  console.log("");

  // ----------------------------------------------------------
  // ЕСЛИ ЛИСТ ПУСТОЙ
  //
  // В таком случае дальнейший анализ не имеет смысла.
  // ----------------------------------------------------------
  if (rows.length === 0) {
    console.log("Лист пуст.");
    return;
  }

  // ----------------------------------------------------------
  // ПЕРВАЯ СТРОКА ПРИНИМАЕТСЯ ЗА ЗАГОЛОВКИ
  //
  // На данном этапе мы только выводим,
  // что реально находится в первой строке Excel.
  //
  // Никаких предположений о названиях колонок не делаем.
  // ----------------------------------------------------------
  const headers = rows[0].map(normalizeText);

  console.log("Заголовки колонок:");
  console.log("");

  headers.forEach((header, index) => {
    // 65 — код символа A.
    // Для первых 26 колонок получаем A, B, C и т.д.
    const excelColumn =
      index < 26 ? String.fromCharCode(65 + index) : `#${index + 1}`;

    console.log(
      `${excelColumn} (${index + 1}): ${header || "[пустой заголовок]"}`,
    );
  });

  console.log("");

  // ----------------------------------------------------------
  // СЧИТАЕМ НЕПУСТЫЕ И ПУСТЫЕ СТРОКИ
  //
  // Строка считается пустой,
  // если во всех её ячейках нет значений.
  // ----------------------------------------------------------
  const dataRows = rows.slice(1);

  let emptyRowsCount = 0;
  let nonEmptyRowsCount = 0;

  for (const row of dataRows) {
    const hasData = row.some((value) => normalizeText(value) !== "");

    if (hasData) {
      nonEmptyRowsCount += 1;
    } else {
      emptyRowsCount += 1;
    }
  }

  // ----------------------------------------------------------
  // ИЩЕМ МАКСИМАЛЬНОЕ КОЛИЧЕСТВО КОЛОНОК
  //
  // Это помогает заметить строки,
  // которые выходят за предполагаемую структуру таблицы.
  // ----------------------------------------------------------
  const maximumColumns = rows.reduce(
    (maximum, row) => Math.max(maximum, row.length),
    0,
  );

  // ----------------------------------------------------------
  // ВЫВОДИМ ОСНОВНУЮ СТАТИСТИКУ
  // ----------------------------------------------------------
  console.log("Статистика:");
  console.log(`Строк с данными: ${nonEmptyRowsCount}`);
  console.log(`Полностью пустых строк: ${emptyRowsCount}`);
  console.log(`Максимальное количество колонок: ${maximumColumns}`);
  console.log("");

  // ----------------------------------------------------------
  // ПОКАЗЫВАЕМ ПЕРВЫЕ 5 НЕПУСТЫХ СТРОК
  //
  // Это диагностический просмотр.
  //
  // Он нужен, чтобы увидеть реальные значения
  // непосредственно до написания логики импорта.
  //
  // Пароли, PostgreSQL и другие данные здесь не используются.
  // ----------------------------------------------------------
  console.log("Первые 5 непустых строк данных:");
  console.log("");

  const firstRows = dataRows
    .map((row, index) => ({
      excelRowNumber: index + 2,
      row,
    }))
    .filter(({ row }) => row.some((value) => normalizeText(value) !== ""))
    .slice(0, 5);

  for (const item of firstRows) {
    console.log(`Строка Excel ${item.excelRowNumber}:`);

    item.row.forEach((value, index) => {
      const normalizedValue = normalizeText(value);

      if (normalizedValue === "") {
        return;
      }

      console.log(`  Колонка ${index + 1}: ${normalizedValue}`);
    });

    console.log("");
  }

  // ----------------------------------------------------------
  // ФИНАЛЬНОЕ СООБЩЕНИЕ
  //
  // Подчёркиваем, что текущий скрипт ничего
  // в PostgreSQL не записывал.
  // ----------------------------------------------------------
  console.log("==============================================");
  console.log("Анализ завершён.");
  console.log("PostgreSQL НЕ изменялся.");
  console.log("Excel НЕ изменялся.");
  console.log("==============================================");
  console.log("");
}

// ------------------------------------------------------------
// ЗАПУСК АНАЛИЗА
// ------------------------------------------------------------
try {
  analyzeMatGesn();
} catch (error) {
  console.error("");
  console.error("Ошибка анализа Excel:");
  console.error(error);
  console.error("");

  process.exit(1);
}
