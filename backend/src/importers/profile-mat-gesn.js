// ============================================================
// PRICE CONTROL V3
// ПРОФИЛИРОВАНИЕ КОЛОНОК ЛИСТА "МАТ ГЭСН"
//
// Этот скрипт нужен для подробного исследования структуры
// существующего Excel перед переносом данных в PostgreSQL.
//
// Скрипт ТОЛЬКО читает Excel.
//
// Он НЕ:
// - изменяет Excel;
// - подключается к PostgreSQL;
// - создаёт материалы;
// - изменяет существующие данные;
// - удаляет данные.
//
// Цель:
// понять фактическое назначение всех 23 колонок.
// ============================================================

const fs = require("fs");
const path = require("path");
const XLSX = require("xlsx");

// ------------------------------------------------------------
// НАЗВАНИЕ ИССЛЕДУЕМОГО ЛИСТА
// ------------------------------------------------------------
const TARGET_SHEET_NAME = "МАТ ГЭСН";

// ------------------------------------------------------------
// ПОЛУЧАЕМ ПУТЬ К EXCEL ИЗ КОМАНДЫ ЗАПУСКА
//
// Пример:
//
// node src/importers/profile-mat-gesn.js "C:\...\file.xlsx"
// ------------------------------------------------------------
const excelFilePath = process.argv[2];

// ------------------------------------------------------------
// ПРОВЕРЯЕМ, ЧТО ПУТЬ К ФАЙЛУ БЫЛ ПЕРЕДАН
// ------------------------------------------------------------
if (!excelFilePath) {
  console.error("");
  console.error("Не указан путь к Excel-файлу.");
  console.error("");

  process.exit(1);
}

// ------------------------------------------------------------
// ПОЛУЧАЕМ АБСОЛЮТНЫЙ ПУТЬ К EXCEL
// ------------------------------------------------------------
const resolvedExcelPath = path.resolve(excelFilePath);

// ------------------------------------------------------------
// ПРОВЕРЯЕМ, ЧТО ФАЙЛ ДЕЙСТВИТЕЛЬНО СУЩЕСТВУЕТ
// ------------------------------------------------------------
if (!fs.existsSync(resolvedExcelPath)) {
  console.error("");
  console.error("Excel-файл не найден:");
  console.error(resolvedExcelPath);
  console.error("");

  process.exit(1);
}

// ------------------------------------------------------------
// ПРЕОБРАЗОВАНИЕ ЗНАЧЕНИЯ В АККУРАТНЫЙ ТЕКСТ
//
// Пустые значения превращаются в пустую строку.
// Остальные значения очищаются от пробелов по краям.
// ------------------------------------------------------------
function normalizeText(value) {
  if (value === null || value === undefined) {
    return "";
  }

  return String(value).trim();
}

// ------------------------------------------------------------
// ПРЕОБРАЗОВАНИЕ НОМЕРА КОЛОНКИ В БУКВУ EXCEL
//
// Например:
//
// 0  → A
// 1  → B
// 25 → Z
// 26 → AA
//
// Сейчас в МАТ ГЭСН только 23 колонки,
// но функция сделана универсальной.
// ------------------------------------------------------------
function getExcelColumnName(columnIndex) {
  let number = columnIndex + 1;
  let result = "";

  while (number > 0) {
    const remainder = (number - 1) % 26;

    result = String.fromCharCode(65 + remainder) + result;

    number = Math.floor((number - 1) / 26);
  }

  return result;
}

// ------------------------------------------------------------
// ПРОВЕРКА: ПОХОЖЕ ЛИ ЗНАЧЕНИЕ НА ЧИСЛО
//
// Здесь мы только классифицируем данные для статистики.
//
// Сами значения при этом не изменяются.
// ------------------------------------------------------------
function looksLikeNumber(value) {
  const text = normalizeText(value);

  if (text === "") {
    return false;
  }

  // Заменяем запятую на точку только для диагностической
  // проверки числа.
  //
  // Исходное значение Excel не меняется.
  const normalizedNumber = text.replace(",", ".");

  return Number.isFinite(Number(normalizedNumber));
}

// ------------------------------------------------------------
// ОСНОВНАЯ ФУНКЦИЯ ПРОФИЛИРОВАНИЯ
// ------------------------------------------------------------
function profileMatGesn() {
  console.log("");
  console.log("================================================");
  console.log("Price Control V3 — профиль колонок МАТ ГЭСН");
  console.log("================================================");
  console.log("");

  console.log("Excel:");
  console.log(resolvedExcelPath);
  console.log("");

  // ----------------------------------------------------------
  // ЧИТАЕМ EXCEL
  //
  // Никакой записи обратно в Excel здесь нет.
  // ----------------------------------------------------------
  const workbook = XLSX.readFile(resolvedExcelPath, {
    cellDates: true,
    cellFormula: true,
  });

  // ----------------------------------------------------------
  // ПРОВЕРЯЕМ НАЛИЧИЕ НУЖНОГО ЛИСТА
  // ----------------------------------------------------------
  if (!workbook.SheetNames.includes(TARGET_SHEET_NAME)) {
    throw new Error(`Лист "${TARGET_SHEET_NAME}" не найден`);
  }

  // ----------------------------------------------------------
  // ПОЛУЧАЕМ ЛИСТ "МАТ ГЭСН"
  // ----------------------------------------------------------
  const worksheet = workbook.Sheets[TARGET_SHEET_NAME];

  // ----------------------------------------------------------
  // ПРЕОБРАЗУЕМ EXCEL В МАССИВ СТРОК
  //
  // raw: false позволяет получить значения
  // примерно в том виде, как они отображаются в Excel.
  // ----------------------------------------------------------
  const rows = XLSX.utils.sheet_to_json(worksheet, {
    header: 1,
    raw: false,
    defval: "",
    blankrows: true,
  });

  if (rows.length === 0) {
    console.log("Лист пуст.");
    return;
  }

  // ----------------------------------------------------------
  // ПЕРВАЯ СТРОКА — ЗАГОЛОВКИ
  // ----------------------------------------------------------
  const headers = rows[0];

  // ----------------------------------------------------------
  // ОСТАЛЬНЫЕ СТРОКИ — ДАННЫЕ
  // ----------------------------------------------------------
  const dataRows = rows.slice(1);

  // ----------------------------------------------------------
  // ОПРЕДЕЛЯЕМ ФАКТИЧЕСКОЕ КОЛИЧЕСТВО КОЛОНОК
  // ----------------------------------------------------------
  const maximumColumns = rows.reduce(
    (maximum, row) => Math.max(maximum, row.length),
    0,
  );

  console.log(`Всего колонок: ${maximumColumns}`);

  console.log(`Всего строк данных: ${dataRows.length}`);

  console.log("");

  // ==========================================================
  // ПРОХОДИМ ПО КАЖДОЙ КОЛОНКЕ
  //
  // Для каждой колонки собираем:
  //
  // - количество заполненных ячеек;
  // - количество пустых;
  // - количество числовых значений;
  // - количество текстовых значений;
  // - до 10 различных примеров.
  // ==========================================================
  for (let columnIndex = 0; columnIndex < maximumColumns; columnIndex += 1) {
    const columnName = getExcelColumnName(columnIndex);

    const header = normalizeText(headers[columnIndex]);

    let filledCount = 0;
    let emptyCount = 0;
    let numberCount = 0;
    let textCount = 0;

    // --------------------------------------------------------
    // Здесь сохраняем несколько различных примеров,
    // чтобы глазами увидеть фактическое содержимое колонки.
    // --------------------------------------------------------
    const examples = [];

    const exampleSet = new Set();

    // --------------------------------------------------------
    // ПРОВЕРЯЕМ КАЖДУЮ СТРОКУ ДАННОЙ КОЛОНКИ
    // --------------------------------------------------------
    for (const row of dataRows) {
      const value = normalizeText(row[columnIndex]);

      // Пустая ячейка.
      if (value === "") {
        emptyCount += 1;
        continue;
      }

      // Заполненная ячейка.
      filledCount += 1;

      // Определяем, число это или текст.
      if (looksLikeNumber(value)) {
        numberCount += 1;
      } else {
        textCount += 1;
      }

      // ------------------------------------------------------
      // СОБИРАЕМ ДО 10 УНИКАЛЬНЫХ ПРИМЕРОВ
      //
      // Ограничение нужно, чтобы терминал
      // не выводил тысячи значений.
      // ------------------------------------------------------
      if (examples.length < 10 && !exampleSet.has(value)) {
        exampleSet.add(value);

        // Очень длинные значения сокращаем только
        // для удобства просмотра отчёта.
        //
        // Сам Excel при этом не изменяется.
        const shortValue =
          value.length > 150 ? `${value.slice(0, 150)}...` : value;

        examples.push(shortValue);
      }
    }

    // ========================================================
    // ВЫВОД ИНФОРМАЦИИ ПО КОЛОНКЕ
    // ========================================================
    console.log("----------------------------------------------");

    console.log(`Колонка ${columnName} (${columnIndex + 1})`);

    console.log(`Заголовок: ${header || "[пустой заголовок]"}`);

    console.log(`Заполнено: ${filledCount}`);

    console.log(`Пусто: ${emptyCount}`);

    console.log(`Похоже на числа: ${numberCount}`);

    console.log(`Текстовых значений: ${textCount}`);

    console.log("Примеры:");

    if (examples.length === 0) {
      console.log("  [нет значений]");
    } else {
      examples.forEach((example, index) => {
        console.log(`  ${index + 1}. ${example}`);
      });
    }

    console.log("");
  }

  // ----------------------------------------------------------
  // ФИНАЛЬНОЕ СООБЩЕНИЕ
  // ----------------------------------------------------------
  console.log("================================================");
  console.log("Профилирование завершено.");
  console.log("PostgreSQL НЕ изменялся.");
  console.log("Excel НЕ изменялся.");
  console.log("================================================");
  console.log("");
}

// ------------------------------------------------------------
// ЗАПУСК
// ------------------------------------------------------------
try {
  profileMatGesn();
} catch (error) {
  console.error("");
  console.error("Ошибка профилирования МАТ ГЭСН:");
  console.error(error);
  console.error("");

  process.exit(1);
}
